// 政策调价金额写入规则（共享业务规则）
// 用途：写入两个文件前对调价金额做最终加工：
//   - 政策导入文件「调价固定加减钱」列（trip exportTemplate）
//   - 底价检查文件「预计减价」列（ExcelExporter，主行与套餐子行）
// 规则（政策导入平台只接受整数）：
//   1. 计算阶段（CUT_VALUE / 套餐差值）不扣 −1，只保留精确价差（可能带小数），
//      保证数值准确性 —— 携程价本身已按口径向下取整（19.9→19）；
//   2. 写入文件前统一：向下取整（floor）再 −1，即 floor(v) − 1。
//      - 整数价差：v − 1 → 生效价恰 = 携程价(取整) − 1（低1元目标）
//      - 小数价差：floor(v) − 1 → 生效价比携程价(取整) 低 1~2 元（整数调价下的最贴近值）
//      - 负数价差（官网价高于携程价时）：同样 floor(v) − 1（如 -4.5 → -6），略有让利
//      - 0：−1（价差为0即原价等于携程价，写入 −1 后生效低1元）
//   3. null/空/非数字原样透传（写入时自然留空）。
// ============================================================

export function formatPolicyAdjust(v) {
  if (v == null || v === '') return v
  const n = Number(v)
  if (!Number.isFinite(n)) return v
  return Math.floor(n) - 1
}

export default { formatPolicyAdjust }